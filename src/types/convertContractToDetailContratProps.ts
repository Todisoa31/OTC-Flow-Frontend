import { DetailContratProps } from "./contratType";

export function toContractUpdatePayload(data: DetailContratProps) {
  return {
    contratID: data.contratID,
    contrat_type: data.contrat_type,
    contrat_nature: data.contrat_nature,
    contrat_name: data.contrat_name,
    mf_somme_globale_ht_par_mwhc: JSON.stringify(data.mf_somme_globale_ht_par_mwhc),
    mf_volume_total_gwhc: String(data.mf_volume_total_gwhc),
    mf_volume_par_mois_gwhc: String(data.mf_volume_par_mois_gwhc),
    prix_total_ht_par_mwhc: data.prix_total_ht_par_mwhc,
    date_livraison: data.date_livraison,
    duree_contrat_en_mois: data.duree_contrat_en_mois,
    status: data.status,

    contrat_acheteur: data.acheteur && {
      acheteur_nom_societe: data.acheteur.acheteur_nom_societe,
      acheteur_type_societe: data.acheteur.acheteur_type_societe,
      acheteur_capital: data.acheteur.acheteur_capital,
      acheteur_adresse: data.acheteur.acheteur_adresse,
      acheteur_ville: data.acheteur.acheteur_ville,
      acheteur_numero_rcs: data.acheteur.acheteur_numero_rcs,
      acheteur_prenom_nom: data.acheteur.acheteur_prenom_nom,
      acheteur_fonction: data.acheteur.acheteur_fonction,
    },

    contrat_vendeur: data.vendeur && {
      vendeur_nom_societe: data.vendeur.vendeur_nom_societe,
      vendeur_type_societe: data.vendeur.vendeur_type_societe,
      vendeur_capital: data.vendeur.vendeur_capital,
      vendeur_adresse: data.vendeur.vendeur_adresse,
      vendeur_ville: data.vendeur.vendeur_ville,
      vendeur_numero_rcs: data.vendeur.vendeur_numero_rcs,
      vendeur_prenom_nom: data.vendeur.vendeur_prenom_nom,
      vendeur_fonction: data.vendeur.vendeur_fonction,
    },

    contrat_beneficiaire: data.beneficiaire && {
      beneficiaire_nom_societe: data.beneficiaire?.beneficiaire_nom_societe,
      beneficiaire_type_societe: data.beneficiaire?.beneficiaire_type_societe,
      beneficiaire_capital: data.beneficiaire?.beneficiaire_capital,
      beneficiaire_adresse: data.beneficiaire?.beneficiaire_adresse,
      beneficiaire_ville: data.beneficiaire?.beneficiaire_ville,
      beneficiaire_numero_rcs: data.beneficiaire?.beneficiaire_numero_rcs,
      beneficiaire_prenom_nom: data.beneficiaire?.beneficiaire_prenom_nom,
      beneficiaire_fonction: data.beneficiaire?.beneficiaire_fonction
    },
    contrat_mandataire: data.mandataire && {
        mandataire_nom_societe: data.mandataire?.mandataire_nom_societe,
        mandataire_type_societe: data.mandataire?.mandataire_type_societe,
        mandataire_capital: data.mandataire?.mandataire_capital,
        mandataire_adresse: data.mandataire?.mandataire_adresse,
        mandataire_ville: data.mandataire?.mandataire_ville,
        mandataire_numero_rcs: data.mandataire?.mandataire_numero_rcs,
        mandataire_prenom_nom: data.mandataire?.mandataire_prenom_nom,
        mandataire_fonction: data.mandataire?.mandataire_fonction
    },
    contrat_apporteur: data.apporteur && {
        apporteur_affaire_nom_societe: data.apporteur?.apporteur_affaire_nom_societe,
        apporteur_affaire_type_societe: data.apporteur?.apporteur_affaire_type_societe,
        apporteur_affaire_capital: data.apporteur?.apporteur_affaire_capital,
        apporteur_affaire_adresse: data.apporteur?.apporteur_affaire_adresse,
        apporteur_affaire_ville: data.apporteur?.apporteur_affaire_ville,
        apporteur_affaire_numero_rcs: data.apporteur?.apporteur_affaire_numero_rcs,
        apporteur_affaire_prenom_nom: data.apporteur?.apporteur_affaire_prenom_nom,
        apporteur_affaire_fonction: data.apporteur?.apporteur_affaire_fonction
    },
    contrat_signature: data.signature && {
      signature_ville: data.signature.signature_ville,
      signature_date: data.signature.signature_date,
      signature_acheteur_nom_societe: data.signature.signature_acheteur_nom_societe,
      signature_acheteur_prenom_nom: data.signature.signature_acheteur_prenom_nom,
      signature_acheteur_fonction: data.signature.signature_acheteur_fonction,
      signature_vendeur_nom_societe: data.signature.signature_vendeur_nom_societe,
      signature_vendeur_prenom_nom: data.signature.signature_vendeur_prenom_nom,
      signature_vendeur_fonction: data.signature.signature_vendeur_fonction,
      signature_beneficiaire_nom_societe: data.signature.signature_beneficiaire_nom_societe,
      signature_beneficiaire_prenom_nom: data.signature.signature_beneficiaire_prenom_nom,
      signature_beneficiaire_fonction: data.signature.signature_beneficiaire_fonction,
      signature_mandataire_nom_societe: data.signature.signature_mandataire_nom_societe,
      signature_mandataire_prenom_nom: data.signature.signature_mandataire_prenom_nom,
      signature_mandataire_fonction: data.signature.signature_mandataire_fonction,
      signature_apporteur_affaire_nom_societe: data.signature.signature_apporteur_affaire_nom_societe,
      signature_apporteur_affaire_prenom_nom: data.signature.signature_apporteur_affaire_prenom_nom,
      signature_apporteur_affaire_fonction: data.signature.signature_apporteur_affaire_fonction,
    },

    contrat_fiche_op: data.fiche_op && {
      fiche_op_residentiel_applicable: data.fiche_op.fiche_op_residentiel_applicable,
      fiche_op_residentiel_cee: data.fiche_op.fiche_op_residentiel_cee.join(','),
      fiche_op_tertiaire_applicable: data.fiche_op.fiche_op_tertiaire_applicable,
      fiche_op_tertiaire_cee: data.fiche_op.fiche_op_tertiaire_cee.join(','),
      fiche_op_industrie_applicable: data.fiche_op.fiche_op_industrie_applicable,
      fiche_op_industrie_cee: data.fiche_op.fiche_op_industrie_cee.join(','),
      fiche_op_agriculture_applicable: data.fiche_op.fiche_op_agriculture_applicable,
      fiche_op_agriculture_cee: data.fiche_op.fiche_op_agriculture_cee.join(','),
      fiche_op_reseaux_applicable: data.fiche_op.fiche_op_reseaux_applicable,
      fiche_op_reseaux_cee: data.fiche_op.fiche_op_reseaux_cee.join(','),
      fiche_op_transport_applicable: data.fiche_op.fiche_op_transport_applicable,
      fiche_op_transport_cee: data.fiche_op.fiche_op_transport_cee.join(','),
    },

    contrat_rai_op: data.rai_op && {
      rai_op_residentiel_applicable: data.rai_op.rai_op_residentiel_applicable,
      rai_op_residentiel_cee: data.rai_op.rai_op_residentiel_cee,
      rai_op_tertiaire_applicable: data.rai_op.rai_op_tertiaire_applicable,
      rai_op_tertiaire_cee: data.rai_op.rai_op_tertiaire_cee,
      rai_op_industrie_applicable: data.rai_op.rai_op_industrie_applicable,
      rai_op_industrie_cee: data.rai_op.rai_op_industrie_cee,
      rai_op_agriculture_applicable: data.rai_op.rai_op_agriculture_applicable,
      rai_op_agriculture_cee: data.rai_op.rai_op_agriculture_cee,
      rai_op_reseaux_applicable: data.rai_op.rai_op_reseaux_applicable,
      rai_op_reseaux_cee: data.rai_op.rai_op_reseaux_cee,
      rai_op_transport_applicable: data.rai_op.rai_op_transport_applicable,
      rai_op_transport_cee: data.rai_op.rai_op_transport_cee,
    },
  }
}

